#include <iostream>   // ввод/вывод
#include <cstdlib>    // rand
#include <clocale>
using namespace std;

int main()
{
    setlocale(LC_ALL,"Russian");
    const int N = 100;   // максимальная длина массива
    int a[N];            // статический массив
    int n;               // реальная длина массива
    int K;               // номер удаляемого элемента

    cout << "Введите длину массива (не более " << N << "): ";
    cin >> n;
    if (n < 1 || n > N)
    {
        cout << "Неверная длина массива" << endl;
        return 1;
    }

    // 1) формирование массива датчиком случайных чисел
    for (int i = 0; i < n; i++)
        a[i] = rand() % 101 - 50;     // числа от -50 до 50

    // 2) печать исходного массива
    cout << "Исходный массив:" << endl;
    for (int i = 0; i < n; i++)
        cout << a[i] << " ";
    cout << endl;

    // 3) удаление элемента с номером K
    cout << "Введите номер удаляемого элемента (0.." << n - 1
         << "): ";
    cin >> K;
    if (K < 0 || K >= n)
    {
        cout << "Неверный номер элемента" << endl;
        return 1;
    }
    for (int i = K; i < n - 1; i++)
        a[i] = a[i + 1];              // сдвиг влево
    n--;                              // длина уменьшилась

    // 4) вставка после первого чётного элемента
    int I = -1;                       // индекс первого чётного
    for (int i = 0; i < n && I == -1; i++)
        if (a[i] % 2 == 0)
            I = i;

    if (I == -1)
        cout << "Чётных элементов нет, вставки нет" << endl;
    else if (I == 0)
        cout << "Перед первым чётным элементом нет элемента, "
             << "вставки нет" << endl;
    else
    {
        int value = a[I - 1] + 2;     // M[I-1] + 2
        for (int i = n; i > I + 1; i--)
            a[i] = a[i - 1];          // сдвиг вправо
        a[I + 1] = value;
        n++;                          // длина увеличилась
    }

    // 5) печать полученного массива
    cout << "Полученный массив:" << endl;
    for (int i = 0; i < n; i++)
        cout << a[i] << " ";
    cout << endl;

    return 0;
}